-- =========================================================================
-- SUPABASE SCHEMA: exam_seating (Run in SchoolMgt -> SQL Editor)
-- =========================================================================
CREATE SCHEMA IF NOT EXISTS exam_seating;
GRANT USAGE ON SCHEMA exam_seating TO anon, authenticated, service_role;

CREATE TABLE IF NOT EXISTS exam_seating.schools (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    code TEXT UNIQUE NOT NULL,
    phone TEXT UNIQUE NOT NULL,
    pass TEXT NOT NULL,
    active BOOLEAN DEFAULT TRUE,
    created_at TEXT,
    last_login TEXT
);

CREATE TABLE IF NOT EXISTS exam_seating.school_data (
    data_key TEXT PRIMARY KEY,
    school_id TEXT NOT NULL,
    payload JSONB NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS exam_seating.otps (
    phone TEXT PRIMARY KEY,
    otp TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS exam_seating.logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time TEXT NOT NULL,
    school_id TEXT,
    school_name TEXT,
    action TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

GRANT ALL ON ALL TABLES IN SCHEMA exam_seating TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA exam_seating TO anon, authenticated, service_role;
